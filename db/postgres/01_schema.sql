-- Clínica ambulatoria · Grupo 2
-- Fase 3/4: esquema definitivo de PostgreSQL para agenda y citas.
-- PostgreSQL 16. Ejecutar en la NUEVA base 'clinica', no en la base 'poc'.
-- No elimina tablas, citas ni volúmenes. Datos exclusivamente ficticios.
-- Fuente oficial: PostgreSQL para cupos, citas e historial.
-- IDs de profesional, sede y servicio son referencias lógicas a MongoDB;
-- la API debe validarlas contra el catálogo oficial.

BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS cupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profesional_id TEXT NOT NULL CHECK (length(btrim(profesional_id)) > 0),
    sede_id TEXT NOT NULL CHECK (length(btrim(sede_id)) > 0),
    servicio_id TEXT NOT NULL CHECK (length(btrim(servicio_id)) > 0),
    inicio TIMESTAMPTZ NOT NULL,
    fin TIMESTAMPTZ NOT NULL,
    estado TEXT NOT NULL DEFAULT 'DISPONIBLE'
        CHECK (estado IN ('DISPONIBLE', 'BLOQUEADO', 'RESERVADO')),
    bloqueado_hasta TIMESTAMPTZ,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_cupo_intervalo CHECK (fin > inicio),
    CONSTRAINT ck_cupo_bloqueo CHECK (
        (estado = 'BLOQUEADO' AND bloqueado_hasta IS NOT NULL)
        OR (estado <> 'BLOQUEADO' AND bloqueado_hasta IS NULL)
    ),
    -- Impide franjas solapadas para un mismo profesional, incluso entre sedes.
    CONSTRAINT ex_cupo_no_solape
        EXCLUDE USING gist (
            profesional_id WITH =,
            tstzrange(inicio, fin, '[)') WITH &&
        )
);

CREATE INDEX IF NOT EXISTS ix_cupo_profesional_inicio
    ON cupo (profesional_id, inicio);
CREATE INDEX IF NOT EXISTS ix_cupo_sede_inicio
    ON cupo (sede_id, inicio);
CREATE INDEX IF NOT EXISTS ix_cupo_disponibles_inicio
    ON cupo (inicio) WHERE estado = 'DISPONIBLE';
CREATE INDEX IF NOT EXISTS ix_cupo_bloqueos_vencimiento
    ON cupo (bloqueado_hasta) WHERE estado = 'BLOQUEADO';

CREATE TABLE IF NOT EXISTS cita (
    id UUID PRIMARY KEY,
    cupo_id BIGINT NOT NULL REFERENCES cupo (id),
    paciente_id TEXT NOT NULL CHECK (length(btrim(paciente_id)) > 0),
    -- Servicio registrado al reservar para conservar referencia histórica.
    servicio_id TEXT NOT NULL CHECK (length(btrim(servicio_id)) > 0),
    estado TEXT NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA')),
    clave_idempotencia UUID NOT NULL UNIQUE,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizada_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Segunda barrera contra la doble reserva: una cita activa por cupo.
CREATE UNIQUE INDEX IF NOT EXISTS uq_cita_activa_por_cupo
    ON cita (cupo_id)
    WHERE estado IN ('PENDIENTE', 'CONFIRMADA');

CREATE INDEX IF NOT EXISTS ix_cita_paciente_creada
    ON cita (paciente_id, creada_en DESC);
CREATE INDEX IF NOT EXISTS ix_cita_cupo
    ON cita (cupo_id);

CREATE TABLE IF NOT EXISTS evento_cita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id UUID NOT NULL REFERENCES cita (id),
    -- REPROGRAMADA es un tipo de evento, no un estado permanente de la cita.
    tipo TEXT NOT NULL CHECK (
        tipo IN ('CREADA', 'CONFIRMADA', 'CANCELADA', 'REPROGRAMADA')
    ),
    estado_anterior TEXT CHECK (
        estado_anterior IS NULL OR
        estado_anterior IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA')
    ),
    estado_nuevo TEXT NOT NULL CHECK (
        estado_nuevo IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA')
    ),
    cupo_anterior_id BIGINT REFERENCES cupo (id),
    cupo_nuevo_id BIGINT REFERENCES cupo (id),
    actor_id TEXT NOT NULL CHECK (length(btrim(actor_id)) > 0),
    actor_rol TEXT NOT NULL CHECK (
        actor_rol IN ('PACIENTE', 'RECEPCIONISTA', 'ADMINISTRADOR', 'SISTEMA')
    ),
    ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_evento_reprogramacion CHECK (
        tipo <> 'REPROGRAMADA'
        OR (cupo_anterior_id IS NOT NULL
            AND cupo_nuevo_id IS NOT NULL
            AND cupo_anterior_id <> cupo_nuevo_id)
    )
);

CREATE INDEX IF NOT EXISTS ix_evento_cita_orden
    ON evento_cita (cita_id, id);

-- La API debe realizar reserva/cancelación/reprogramación con
-- transacciones locales que actualicen cupo + cita + evento juntos.
-- Para reservar:
--   UPDATE cupo SET estado='RESERVADO', actualizado_en=now()
--   WHERE id=$1 AND estado='DISPONIBLE' AND inicio>now() RETURNING id;
-- Si devuelve 0 filas: HTTP 409 (o 404 si no existe).
-- Reintentos: la API debe comprobar que la misma clave UUID corresponde
-- al MISMO paciente y a la MISMA petición; jamás divulgar citas ajenas.
-- Para cancelar: bloquear la cita, verificar estado y propiedad, actualizar
-- cita y cupo, insertar evento, todo antes de COMMIT.
-- Para reprogramar: bloquear cita y ambos cupos en orden fijo, ocupar el nuevo,
-- liberar el antiguo, actualizar cita e insertar evento REPROGRAMADA.
-- Hold: el vencimiento NO libera un cupo automáticamente solo por la fecha.
-- Un worker o una operación transaccional debe liberar BLOQUEADO vencidos,
-- sin afectar citas reservadas ni violar la regla de un cupo activo.
-- El responsable de actualizar 'actualizado_en' es la API por ahora.
-- El historial se considera append-only por contrato de la API;
-- restringir UPDATE/DELETE con permisos de rol antes del despliegue final.

COMMIT;
